class PrintDemo {
	public static void main(String args[]) {
		System.out.println("My name is Piriththi"); //Using println
		System.out.println("My father name is Ramesh");
		System.out.println("My age is 22");
		
		System.out.println();
		
		System.out.print("My name is Piriththi"); //Using print
		System.out.print("My father name is Ramesh");
		System.out.print("My age is 22");
		
		System.out.println();
		
		//Using print with \n
		System.out.print("My name is Piriththi\n");
		System.out.print("My father name is Ramesh\n");
		System.out.print("My age is 22\n");
		
	}
}